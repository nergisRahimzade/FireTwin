"""Data-quality report: which cells and rows are empty in the NASA tables (docs/data_quality.md).

Three views, all computed from the files in the repo:
1. each raw PSI table: rows, and how many cells are empty per column;
2. each cleaned table: empty cells per unified-table column and rows with an unknown outcome;
3. the unified table: the rows left out of it (no O2 value), and what is empty in what stayed.
Run by build_table.py, or by hand: `python data/pipeline/data_quality.py`.
"""

from __future__ import annotations

import json
import logging

import pandas as pd
from psi_sources import CLEAN_DIR, OTHER_DIR, RAW_DIR, ROOT, SOURCES, read_rows

log = logging.getLogger("data_quality")

REPORT_MD = ROOT / "docs" / "data_quality.md"
REPORT_JSON = ROOT / "data" / "processed" / "data_quality.json"
UNIFIED_FIELDS = ["o2_pct", "pressure_kpa", "flow_cm_s", "spread_rate_mm_s"]
EMPTY_WORDS = {"", "n/a", "na", "none", "-", "?", "video"}


def _is_empty(value: str) -> bool:
    return value.strip().lower() in EMPTY_WORDS


def profile_raw() -> list[dict]:
    """Per raw PSI table: row count and the columns that have empty cells."""
    out = []
    for source in SOURCES:
        path = RAW_DIR / source.file_name
        if not path.exists():
            out.append({"table": source.name, "file": source.file_name, "missing_file": True})
            continue
        rows = [r for r in read_rows(path) if any(v for v in r.values())]
        columns = {}
        for column in rows[0] if rows else []:
            empty = sum(_is_empty(r.get(column, "")) for r in rows)
            if empty:
                columns[column] = empty
        out.append(
            {
                "table": source.name,
                "file": source.file_name,
                "rows": len(rows),
                "empty_cells_by_column": columns,
            }
        )
    return out


def profile_clean(unified: pd.DataFrame) -> dict:
    """Empty fields per cleaned table, rows left out of the unified table, what stays empty."""
    per_table = []
    left_out: dict[str, list[str]] = {}
    for path in sorted(CLEAN_DIR.glob("*.csv")):
        table = pd.read_csv(path)
        names = {f: int(table[f].isna().sum()) for f in UNIFIED_FIELDS}
        entry = {
            "file": path.name,
            "rows": int(len(table)),
            "empty_fields": names,
            "rows_without_o2": int(table["o2_pct"].isna().sum()),
        }
        per_table.append(entry)
        gone = table.loc[~table["test_id"].isin(unified["test_id"]), "test_id"].tolist()
        if gone:
            left_out[path.name] = gone
    stay = {f: int(unified[f].isna().sum()) for f in UNIFIED_FIELDS}
    by_outcome = unified.groupby(["investigation", "outcome"]).size().unstack(fill_value=0)
    return {
        "clean_tables": per_table,
        "left_out_of_unified_table": {
            k: {"count": len(v), "test_ids": v} for k, v in left_out.items()
        },
        "unified_rows": int(len(unified)),
        "unified_empty_fields": stay,
        "unified_outcomes": json.loads(by_outcome.to_json(orient="index")),
        "other_tables": sorted(p.name for p in OTHER_DIR.glob("*.csv"))
        if OTHER_DIR.exists()
        else [],
    }


def render(raw: list[dict], clean: dict) -> str:
    lines = [
        "# Data quality report",
        "",
        "Generated by `data/pipeline/data_quality.py`; do not edit by hand.",
        "",
    ]
    lines += [
        "## 1. Raw PSI tables: empty cells",
        "",
        "| Table | Rows | Columns with empty cells (count) |",
        "|---|---|---|",
    ]
    for t in raw:
        if t.get("missing_file"):
            lines.append(f"| {t['table']} | FILE MISSING | {t['file']} |")
            continue
        cols = ", ".join(f"{c} ({n})" for c, n in t["empty_cells_by_column"].items()) or "none"
        lines.append(f"| {t['table']} | {t['rows']} | {cols} |")
    lines += [
        "",
        "## 2. Cleaned test tables: empty fields",
        "",
        "| File | Rows | no O2 | no pressure | no flow | no spread rate |",
        "|---|---|---|---|---|---|",
    ]
    for t in clean["clean_tables"]:
        e = t["empty_fields"]
        lines.append(
            f"| {t['file']} | {t['rows']} | {e['o2_pct']} | {e['pressure_kpa']} | "
            f"{e['flow_cm_s']} | {e['spread_rate_mm_s']} |"
        )
    lines += ["", "## 3. Rows left out of the unified table (no O2 value)", ""]
    for name, info in clean["left_out_of_unified_table"].items():
        lines.append(f"- **{name}**: {info['count']} rows, e.g. {', '.join(info['test_ids'][:4])}")
    if not clean["left_out_of_unified_table"]:
        lines.append("- none")
    e = clean["unified_empty_fields"]
    lines += [
        "",
        f"## 4. Unified table: {clean['unified_rows']} rows",
        "",
        f"Empty fields: no pressure {e['pressure_kpa']}, no flow {e['flow_cm_s']}, "
        f"no spread rate {e['spread_rate_mm_s']}.",
        "",
        "| Investigation | burned | extinguished | unknown |",
        "|---|---|---|---|",
    ]
    for inv, counts in clean["unified_outcomes"].items():
        lines.append(
            f"| {inv} | {counts.get('burned', 0)} | {counts.get('extinguished', 0)} | "
            f"{counts.get('unknown', 0)} |"
        )
    lines += [
        "",
        "Tables kept outside the burn-test table (not burn tests): "
        + ", ".join(clean["other_tables"])
        + ".",
        "",
    ]
    return "\n".join(lines)


def write_report(unified: pd.DataFrame) -> None:
    try:
        raw, clean = profile_raw(), profile_clean(unified)
        REPORT_MD.write_text(render(raw, clean), encoding="utf-8")
        REPORT_JSON.write_text(json.dumps({"raw": raw, **clean}, indent=2) + "\n", encoding="utf-8")
    except Exception:
        log.exception("write_report failed")
        raise


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(name)s: %(message)s")
    write_report(pd.read_parquet(ROOT / "data" / "processed" / "tests.parquet"))
    log.info("wrote %s", REPORT_MD)


if __name__ == "__main__":
    main()
